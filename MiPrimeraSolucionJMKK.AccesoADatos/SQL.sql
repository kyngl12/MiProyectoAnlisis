-- =====================================================================
-- SECCION 4: EMPLEADOS
-- NOTA DE DISENO (PK compuesta innecesaria): la tabla original definia
-- PRIMARY KEY (ID_EMPLEADO, CEDULA) y ADEMAS un UNIQUE(ID_EMPLEADO).
-- Si ID_EMPLEADO ya es unico por si solo, la PK compuesta no aporta
-- nada: cualquier busqueda por ID_EMPLEADO (la forma normal de
-- trabajar de una app .NET con Entity/ADO.NET) termina golpeando un
-- indice mas pesado de lo necesario, y la relacion 1 a 1 real con
-- CEDULA se expresa mejor como UNIQUE simple. Se corrige dejando
-- ID_EMPLEADO como PK y CEDULA como UNIQUE + FK. Mismo caso en
-- PUBROCK_PROVEEDOR_TB. Ninguna columna fue eliminada ni renombrada.
-- =====================================================================
CREATE TABLE PUBROCK_PUESTO_TB (
    ID_PUESTO     INT IDENTITY(1,1) NOT NULL,
    NOMBRE_PUESTO VARCHAR(100) NOT NULL,
    DESCRIPCION   VARCHAR(255),
    ID_ESTADO     INT NOT NULL DEFAULT 1,
    CONSTRAINT PK_PUBROCK_PUESTO_TB PRIMARY KEY (ID_PUESTO),
    CONSTRAINT FK_PUBROCK_PUESTO_ESTADO FOREIGN KEY (ID_ESTADO) REFERENCES PUBROCK_ESTADO_TB(ID_ESTADO)
);
GO

