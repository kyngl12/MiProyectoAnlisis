        EV.DESCRIPCION     AS Estado,
        V.TOTAL_VENTA      AS Total,
        ISNULL((SELECT SUM(SUBTOTAL) FROM PUBROCK_DETALLE_VENTA_TB WHERE ID_VENTA = V.ID_VENTA AND ID_ESTADO = 1), 0) AS SubtotalGeneral,
        ISNULL((SELECT SUM(MONTO_IMPUESTO) FROM PUBROCK_VENTA_IMPUESTO_TB WHERE ID_VENTA = V.ID_VENTA AND ID_ESTADO = 1), 0) AS TotalImpuestos,
        V.FECHA_ANULACION  AS FechaAnulacion,
        V.MOTIVO_ANULACION AS MotivoAnulacion
    FROM PUBROCK_VENTA_TB V
    INNER JOIN PUBROCK_ESTADO_VENTA_TB EV ON EV.ID_ESTADO_VENTA = V.ID_ESTADO_VENTA
    WHERE V.ID_VENTA = @ID_VENTA;

    SELECT
        DV.ID_DETALLE_VENTA AS IdDetalleVenta,
        DV.ID_PRODUCTO      AS IdProducto,
        P.NOMBRE_PRODUCTO   AS NombreProducto,
        DV.CANTIDAD         AS Cantidad,
        DV.PRECIO_UNITARIO  AS PrecioUnitario,
        DV.SUBTOTAL         AS Subtotal
    FROM PUBROCK_DETALLE_VENTA_TB DV
    INNER JOIN PUBROCK_PRODUCTO_TB P ON P.ID_PRODUCTO = DV.ID_PRODUCTO
    WHERE DV.ID_VENTA = @ID_VENTA AND DV.ID_ESTADO = 1;
END
GO

-- GPV-004: Busqueda parcial de productos activos y con stock
-- disponible, por nombre, codigo de barras o categoria.
IF OBJECT_ID('SP_PUBROCK_BUSCAR_PRODUCTOS', 'P') IS NOT NULL
    DROP PROCEDURE SP_PUBROCK_BUSCAR_PRODUCTOS;
GO

CREATE PROCEDURE SP_PUBROCK_BUSCAR_PRODUCTOS
    @TEXTO_BUSQUEDA VARCHAR(100) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        P.ID_PRODUCTO            AS IdProducto,
        P.CODIGO_BARRAS          AS Codigo,
        P.NOMBRE_PRODUCTO        AS Nombre,
        P.PRECIO_VENTA           AS Precio,
        ISNULL(I.STOCK_ACTUAL,0) AS StockDisponible,
        C.NOMBRE_CATEGORIA       AS Categoria
    FROM PUBROCK_PRODUCTO_TB P
    INNER JOIN PUBROCK_CATEGORIA_PRODUCTO_TB C ON C.ID_CATEGORIA_PRODUCTO = P.ID_CATEGORIA_PRODUCTO
    LEFT JOIN PUBROCK_INVENTARIO_TB I ON I.ID_PRODUCTO = P.ID_PRODUCTO
    WHERE P.ID_ESTADO = 1
      AND ISNULL(I.STOCK_ACTUAL,0) > 0
      AND (
            @TEXTO_BUSQUEDA IS NULL OR @TEXTO_BUSQUEDA = ''
            OR P.NOMBRE_PRODUCTO LIKE '%' + @TEXTO_BUSQUEDA + '%'
            OR P.CODIGO_BARRAS LIKE '%' + @TEXTO_BUSQUEDA + '%'
            OR C.NOMBRE_CATEGORIA LIKE '%' + @TEXTO_BUSQUEDA + '%'
      )
    ORDER BY P.NOMBRE_PRODUCTO;
END
GO

