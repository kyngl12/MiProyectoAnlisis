-- SECCION 18: INDICES DE APOYO SOBRE LLAVES FORANEAS
-- SQL Server NO crea automaticamente un indice sobre las columnas FK
-- (solo sobre la PK referenciada). Sin estos indices, los JOIN y los
-- borrados/actualizaciones en cascada logica recorren la tabla
-- completa. Se agregan sobre las columnas mas consultadas por un
-- sistema de punto de venta / restaurante.
-- =====================================================================
CREATE INDEX IX_PUBROCK_PROVINCIA_PAIS               ON PUBROCK_PROVINCIA_TB(ID_PAIS);
CREATE INDEX IX_PUBROCK_CANTON_PROVINCIA              ON PUBROCK_CANTON_TB(ID_PROVINCIA);
CREATE INDEX IX_PUBROCK_DISTRITO_CANTON               ON PUBROCK_DISTRITO_TB(ID_CANTON);
CREATE INDEX IX_PUBROCK_USUARIO_TIPO_USUARIO          ON PUBROCK_USUARIO_TB(ID_TIPO_USUARIO);
