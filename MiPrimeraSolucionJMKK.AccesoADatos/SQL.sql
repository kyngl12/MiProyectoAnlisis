-- =====================================================================
-- SECCION 0: CREACION DE LA BASE DE DATOS
-- =====================================================================
IF DB_ID('PUBROCK_CR') IS NOT NULL
BEGIN
    ALTER DATABASE PUBROCK_CR SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE PUBROCK_CR;
END;
GO

CREATE DATABASE PUBROCK_CR;
GO

USE PUBROCK_CR;
GO

-- Habilita a 'sa' como propietario de la base para evitar el error
-- "Error no especificado" al crear diagramas de base de datos en SSMS.
-- (Se conserva porque es inofensivo; se retiraron mas adelante todos
--  los comandos verdaderamente peligrosos del script original.)
ALTER AUTHORIZATION ON DATABASE::PUBROCK_CR TO sa;
GO


-- =====================================================================
-- SECCION 1: TABLA MAESTRA DE ESTADOS
-- Todas las tablas del sistema usan ID_ESTADO como bandera logica de
-- activo/inactivo (borrado logico). Se crea primero porque es
-- referenciada por practicamente todo el modelo.
-- =====================================================================
CREATE TABLE PUBROCK_ESTADO_TB (
    ID_ESTADO   INT IDENTITY(1,1) NOT NULL,
    DESCRIPCION VARCHAR(100) NOT NULL,
    CONSTRAINT PK_PUBROCK_ESTADO_TB PRIMARY KEY (ID_ESTADO),
    CONSTRAINT UQ_PUBROCK_ESTADO_DESCRIPCION UNIQUE (DESCRIPCION)
);
GO

-- Datos base indispensables: sin estos registros, cualquier INSERT
-- posterior que use ID_ESTADO = 1 fallaria por violacion de FK.
-- (En el script original esta carga faltaba por completo.)
INSERT INTO PUBROCK_ESTADO_TB (DESCRIPCION) VALUES
('Activo'),
('Inactivo');
GO


-- =====================================================================
-- SECCION 2: UBICACIONES GEOGRAFICAS (jerarquia Pais -> Provincia ->
-- Canton -> Distrito). Se agregan las relaciones jerarquicas faltantes
-- solicitadas (mejora de integridad referencial), sin eliminar ni
-- renombrar ninguna columna existente.
-- =====================================================================
