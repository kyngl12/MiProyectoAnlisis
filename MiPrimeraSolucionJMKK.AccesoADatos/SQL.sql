-- GPV-001: Registrar una venta (no descuenta inventario todavia).
-- @RESULTADO: 1 = OK | -1 producto no existe/inactivo | -2 cantidad
-- invalida | -3 stock insuficiente | -4 sin productos | -99 error.
IF OBJECT_ID('SP_PUBROCK_REGISTRAR_VENTA', 'P') IS NOT NULL
    DROP PROCEDURE SP_PUBROCK_REGISTRAR_VENTA;
GO

CREATE PROCEDURE SP_PUBROCK_REGISTRAR_VENTA
    @ID_EMPLEADO INT,
    @ID_CLIENTE  INT = NULL,
    @DETALLE     PUBROCK_DETALLE_VENTA_TIPO_TB READONLY,
    @ID_VENTA    INT OUTPUT,
    @RESULTADO   INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @ID_VENTA = NULL;
    SET @RESULTADO = 0;

    IF NOT EXISTS (SELECT 1 FROM @DETALLE)
    BEGIN
        SET @RESULTADO = -4;
        RETURN;
    END

    IF EXISTS (SELECT 1 FROM @DETALLE WHERE CANTIDAD <= 0)
    BEGIN
        SET @RESULTADO = -2;
        RETURN;
    END

    IF EXISTS (
        SELECT 1 FROM @DETALLE D
        LEFT JOIN PUBROCK_PRODUCTO_TB P ON P.ID_PRODUCTO = D.ID_PRODUCTO AND P.ID_ESTADO = 1
        WHERE P.ID_PRODUCTO IS NULL
    )
    BEGIN
        SET @RESULTADO = -1;
        RETURN;
    END

    IF EXISTS (
        SELECT 1 FROM @DETALLE D
        INNER JOIN PUBROCK_INVENTARIO_TB I ON I.ID_PRODUCTO = D.ID_PRODUCTO
        WHERE I.STOCK_ACTUAL < D.CANTIDAD
    )
    BEGIN
        SET @RESULTADO = -3;
        RETURN;
    END

    DECLARE @ID_ESTADO_PENDIENTE INT = (SELECT TOP 1 ID_ESTADO_VENTA FROM PUBROCK_ESTADO_VENTA_TB WHERE DESCRIPCION = 'Pendiente');
    DECLARE @ID_IMPUESTO INT = (SELECT TOP 1 ID_IMPUESTO FROM PUBROCK_IMPUESTO_TB WHERE ID_ESTADO = 1 ORDER BY ID_IMPUESTO);
    DECLARE @PORCENTAJE_IMPUESTO DECIMAL(5,2) = (SELECT PORCENTAJE FROM PUBROCK_IMPUESTO_TB WHERE ID_IMPUESTO = @ID_IMPUESTO);

    BEGIN TRAN;
    BEGIN TRY
        INSERT INTO PUBROCK_VENTA_TB (FECHA_VENTA, TOTAL_VENTA, ID_CLIENTE, ID_EMPLEADO, ID_ESTADO, ID_ESTADO_VENTA)
        VALUES (GETDATE(), 0, @ID_CLIENTE, @ID_EMPLEADO, 1, @ID_ESTADO_PENDIENTE);

        SET @ID_VENTA = SCOPE_IDENTITY();

        INSERT INTO PUBROCK_DETALLE_VENTA_TB (CANTIDAD, PRECIO_UNITARIO, SUBTOTAL, ID_VENTA, ID_PRODUCTO, ID_ESTADO)
        SELECT D.CANTIDAD, P.PRECIO_VENTA, D.CANTIDAD * P.PRECIO_VENTA, @ID_VENTA, D.ID_PRODUCTO, 1
        FROM @DETALLE D
        INNER JOIN PUBROCK_PRODUCTO_TB P ON P.ID_PRODUCTO = D.ID_PRODUCTO;

        DECLARE @SUBTOTAL_GENERAL DECIMAL(10,2) = (SELECT SUM(SUBTOTAL) FROM PUBROCK_DETALLE_VENTA_TB WHERE ID_VENTA = @ID_VENTA);
        DECLARE @MONTO_IMPUESTO DECIMAL(10,2) = ISNULL(@SUBTOTAL_GENERAL * (@PORCENTAJE_IMPUESTO / 100.0), 0);
        DECLARE @TOTAL DECIMAL(10,2) = @SUBTOTAL_GENERAL + @MONTO_IMPUESTO;

        UPDATE PUBROCK_VENTA_TB SET TOTAL_VENTA = @TOTAL WHERE ID_VENTA = @ID_VENTA;

        IF @ID_IMPUESTO IS NOT NULL AND @MONTO_IMPUESTO > 0
        BEGIN
            INSERT INTO PUBROCK_VENTA_IMPUESTO_TB (ID_VENTA, ID_IMPUESTO, MONTO_IMPUESTO, ID_ESTADO)
            VALUES (@ID_VENTA, @ID_IMPUESTO, @MONTO_IMPUESTO, 1);
        END

        COMMIT TRAN;
        SET @RESULTADO = 1;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK TRAN;
        SET @RESULTADO = -99;
        SET @ID_VENTA = NULL;
    END CATCH
END
GO

-- GPV-002 / GPV-006: Procesar el pago de una venta: valida, descuenta
-- inventario (nunca permite stock negativo) y genera el comprobante
-- (factura), todo dentro de una unica transaccion con rollback ante
-- cualquier error.
-- @RESULTADO: 1 = OK | -1 no existe | -2 ya pagada | -3 anulada |
-- -4 sin productos | -5 stock insuficiente | -99 error.
IF OBJECT_ID('SP_PUBROCK_PROCESAR_VENTA', 'P') IS NOT NULL
    DROP PROCEDURE SP_PUBROCK_PROCESAR_VENTA;
GO

CREATE PROCEDURE SP_PUBROCK_PROCESAR_VENTA
    @ID_VENTA     INT,
    @ID_TIPO_PAGO INT,
    @ID_FACTURA   INT OUTPUT,
    @RESULTADO    INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET @RESULTADO = 0;
    SET @ID_FACTURA = NULL;

    DECLARE @ID_ESTADO_PAGADA INT = (SELECT TOP 1 ID_ESTADO_VENTA FROM PUBROCK_ESTADO_VENTA_TB WHERE DESCRIPCION = 'Pagada');
    DECLARE @ID_ESTADO_ANULADA INT = (SELECT TOP 1 ID_ESTADO_VENTA FROM PUBROCK_ESTADO_VENTA_TB WHERE DESCRIPCION = 'Anulada');
    DECLARE @ID_TIPO_MOV_SALIDA INT = (SELECT TOP 1 ID_TIPO_MOVIMIENTO FROM PUBROCK_TIPO_MOVIMIENTO_INVENTARIO_TB WHERE DESCRIPCION = 'Salida por Venta' ORDER BY ID_TIPO_MOVIMIENTO);

    DECLARE @ESTADO_ACTUAL INT;
    SELECT @ESTADO_ACTUAL = ID_ESTADO_VENTA FROM PUBROCK_VENTA_TB WHERE ID_VENTA = @ID_VENTA AND ID_ESTADO = 1;

    IF @ESTADO_ACTUAL IS NULL
    BEGIN
        SET @RESULTADO = -1;
        RETURN;
    END

    IF @ESTADO_ACTUAL = @ID_ESTADO_PAGADA
    BEGIN
        SET @RESULTADO = -2;
        RETURN;
    END

    IF @ESTADO_ACTUAL = @ID_ESTADO_ANULADA
    BEGIN
        SET @RESULTADO = -3;
        RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM PUBROCK_DETALLE_VENTA_TB WHERE ID_VENTA = @ID_VENTA AND ID_ESTADO = 1)
    BEGIN
        SET @RESULTADO = -4;
        RETURN;
    END

    IF EXISTS (
        SELECT 1
        FROM PUBROCK_DETALLE_VENTA_TB DV
        INNER JOIN PUBROCK_INVENTARIO_TB I ON I.ID_PRODUCTO = DV.ID_PRODUCTO
        WHERE DV.ID_VENTA = @ID_VENTA AND DV.ID_ESTADO = 1
          AND I.STOCK_ACTUAL < DV.CANTIDAD
    )
    BEGIN
        SET @RESULTADO = -5;
        RETURN;
    END

    BEGIN TRAN;
    BEGIN TRY
        UPDATE I
        SET I.STOCK_ACTUAL = I.STOCK_ACTUAL - DV.CANTIDAD,
            I.FECHA_ULTIMA_ACTUALIZACION = GETDATE()
        FROM PUBROCK_INVENTARIO_TB I
        INNER JOIN PUBROCK_DETALLE_VENTA_TB DV ON DV.ID_PRODUCTO = I.ID_PRODUCTO
        WHERE DV.ID_VENTA = @ID_VENTA AND DV.ID_ESTADO = 1;

        IF EXISTS (SELECT 1 FROM PUBROCK_INVENTARIO_TB WHERE STOCK_ACTUAL < 0)
        BEGIN
            RAISERROR('Stock insuficiente durante el procesamiento de la venta', 16, 1);
        END

        INSERT INTO PUBROCK_MOVIMIENTO_INVENTARIO_TB (FECHA_MOVIMIENTO, CANTIDAD, OBSERVACION, ID_INVENTARIO, ID_TIPO_MOVIMIENTO, ID_ESTADO)
        SELECT GETDATE(), -DV.CANTIDAD, 'Descuento por venta #' + CAST(@ID_VENTA AS VARCHAR(20)), I.ID_INVENTARIO, @ID_TIPO_MOV_SALIDA, 1
        FROM PUBROCK_DETALLE_VENTA_TB DV
        INNER JOIN PUBROCK_INVENTARIO_TB I ON I.ID_PRODUCTO = DV.ID_PRODUCTO
        WHERE DV.ID_VENTA = @ID_VENTA AND DV.ID_ESTADO = 1;

        UPDATE PUBROCK_VENTA_TB SET ID_ESTADO_VENTA = @ID_ESTADO_PAGADA WHERE ID_VENTA = @ID_VENTA;

        DECLARE @MONTO_TOTAL DECIMAL(10,2) = (SELECT TOTAL_VENTA FROM PUBROCK_VENTA_TB WHERE ID_VENTA = @ID_VENTA);
        DECLARE @NUMERO_FACTURA VARCHAR(100) = 'FAC-' + CAST(@ID_VENTA AS VARCHAR(20)) + '-' + CONVERT(VARCHAR(8), GETDATE(), 112);

        INSERT INTO PUBROCK_FACTURA_TB (NUMERO_FACTURA, FECHA_FACTURA, MONTO_TOTAL, ID_VENTA, ID_TIPO_PAGO, ID_ESTADO)
        VALUES (@NUMERO_FACTURA, GETDATE(), @MONTO_TOTAL, @ID_VENTA, @ID_TIPO_PAGO, 1);

        SET @ID_FACTURA = SCOPE_IDENTITY();

        COMMIT TRAN;
        SET @RESULTADO = 1;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK TRAN;
        SET @RESULTADO = -99;
        SET @ID_FACTURA = NULL;
    END CATCH
END
GO

-- GPV-003 / GPV-006: Anular una venta (borrado logico por estado).
-- Si estaba Pagada, restaura el inventario dentro de la misma
-- transaccion. Nunca elimina registros fisicos.
-- @RESULTADO: 1 = OK | -1 no existe | -2 ya anulada | -99 error.
IF OBJECT_ID('SP_PUBROCK_ANULAR_VENTA', 'P') IS NOT NULL
    DROP PROCEDURE SP_PUBROCK_ANULAR_VENTA;
GO

CREATE PROCEDURE SP_PUBROCK_ANULAR_VENTA
    @ID_VENTA         INT,
    @MOTIVO_ANULACION VARCHAR(255) = NULL,
    @RESULTADO        INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET @RESULTADO = 0;

    DECLARE @ID_ESTADO_PAGADA  INT = (SELECT TOP 1 ID_ESTADO_VENTA FROM PUBROCK_ESTADO_VENTA_TB WHERE DESCRIPCION = 'Pagada');
    DECLARE @ID_ESTADO_ANULADA INT = (SELECT TOP 1 ID_ESTADO_VENTA FROM PUBROCK_ESTADO_VENTA_TB WHERE DESCRIPCION = 'Anulada');
    DECLARE @ID_TIPO_MOV_ENTRADA INT = (SELECT TOP 1 ID_TIPO_MOVIMIENTO FROM PUBROCK_TIPO_MOVIMIENTO_INVENTARIO_TB WHERE DESCRIPCION = 'Entrada por Anulacion' ORDER BY ID_TIPO_MOVIMIENTO);

    DECLARE @ESTADO_ACTUAL INT;
    SELECT @ESTADO_ACTUAL = ID_ESTADO_VENTA FROM PUBROCK_VENTA_TB WHERE ID_VENTA = @ID_VENTA AND ID_ESTADO = 1;

    IF @ESTADO_ACTUAL IS NULL
    BEGIN
        SET @RESULTADO = -1;
        RETURN;
    END

    IF @ESTADO_ACTUAL = @ID_ESTADO_ANULADA
    BEGIN
        SET @RESULTADO = -2;
        RETURN;
    END

    BEGIN TRAN;
    BEGIN TRY
        IF @ESTADO_ACTUAL = @ID_ESTADO_PAGADA
        BEGIN
            UPDATE I
            SET I.STOCK_ACTUAL = I.STOCK_ACTUAL + DV.CANTIDAD,
                I.FECHA_ULTIMA_ACTUALIZACION = GETDATE()
            FROM PUBROCK_INVENTARIO_TB I
            INNER JOIN PUBROCK_DETALLE_VENTA_TB DV ON DV.ID_PRODUCTO = I.ID_PRODUCTO
            WHERE DV.ID_VENTA = @ID_VENTA AND DV.ID_ESTADO = 1;

            INSERT INTO PUBROCK_MOVIMIENTO_INVENTARIO_TB (FECHA_MOVIMIENTO, CANTIDAD, OBSERVACION, ID_INVENTARIO, ID_TIPO_MOVIMIENTO, ID_ESTADO)
            SELECT GETDATE(), DV.CANTIDAD, 'Restitucion por anulacion de venta #' + CAST(@ID_VENTA AS VARCHAR(20)), I.ID_INVENTARIO, @ID_TIPO_MOV_ENTRADA, 1
            FROM PUBROCK_DETALLE_VENTA_TB DV
            INNER JOIN PUBROCK_INVENTARIO_TB I ON I.ID_PRODUCTO = DV.ID_PRODUCTO
            WHERE DV.ID_VENTA = @ID_VENTA AND DV.ID_ESTADO = 1;
        END

        UPDATE PUBROCK_VENTA_TB
        SET ID_ESTADO_VENTA  = @ID_ESTADO_ANULADA,
            FECHA_ANULACION  = GETDATE(),
            MOTIVO_ANULACION = @MOTIVO_ANULACION
        WHERE ID_VENTA = @ID_VENTA;

        COMMIT TRAN;
        SET @RESULTADO = 1;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK TRAN;
        SET @RESULTADO = -99;
    END CATCH
END
